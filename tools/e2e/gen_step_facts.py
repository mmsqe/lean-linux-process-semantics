#!/usr/bin/env python3
"""Write the fetch and decode facts of a riscv64 ELF as a Lean module.

    gen_step_facts.py ELF DECODER MODULE SEGS IMPORT PROOF > Out.lean

DECODER is this repository's `decoder` executable.  Only the facts PROOF names are
written, so regenerate after a proof reaches new code.  The kernel checks every
fact when the module is built, so this script is a convenience, not trusted.  A
compressed instruction is refused: the step lemmas are for 4-byte instructions.
"""
import re
import struct
import subprocess
import sys

PT_LOAD = 1
PF_X = 1


def text_of(path):
    data = open(path, "rb").read()
    phoff = struct.unpack_from("<Q", data, 32)[0]
    phentsize, phnum = struct.unpack_from("<HH", data, 54)
    for i in range(phnum):
        off = phoff + i * phentsize
        ptype, flags = struct.unpack_from("<II", data, off)
        if ptype == PT_LOAD and flags & PF_X:
            p_off, vaddr = struct.unpack_from("<QQ", data, off + 8)
            filesz = struct.unpack_from("<Q", data, off + 32)[0]
            return vaddr, data[p_off:p_off + filesz]
    sys.exit("no executable PT_LOAD in " + path)


def decode_all(decoder, words):
    text = "".join("0x%08x\n" % w for w in words)
    out = subprocess.run([decoder], input=text, capture_output=True, text=True, check=True).stdout
    decoded = {}
    for line in out.splitlines():
        tok, instr, length = line.split("\t")
        if length != "4" or instr == "<none>":
            sys.exit("not a 4-byte instruction: " + line)
        decoded[int(tok, 16)] = instr.replace("LinuxSem.Riscv.", "")
    return decoded


def main():
    if len(sys.argv) != 7:
        sys.exit(__doc__)
    elf, decoder, module, segs, imp, proof = sys.argv[1:]
    used = set(re.findall(r"\b[FD]_[0-9a-f]+\b", open(proof, encoding="utf8").read()))
    vaddr, text = text_of(elf)
    if len(text) % 4:
        sys.exit("text is not a whole number of 4-byte instructions")
    words = [struct.unpack_from("<I", text, i)[0] for i in range(0, len(text), 4)]
    decoded = decode_all(decoder, sorted(set(words)))
    print("/-\n  * %s — fetch and decode facts\n" % module)
    print("  Generated by `tools/e2e/gen_step_facts.py`, and checked here by the kernel.\n-/")
    print("import %s\n" % imp)
    print("set_option autoImplicit false\nset_option maxRecDepth 400000\nset_option maxHeartbeats 4000000\n")
    print("open LinuxSem.Riscv\nopen LinuxSem.LinuxProcessSem.RiscvSemantics\n")
    print("namespace %s\n" % module)
    for i, word in enumerate(words):
        addr = vaddr + 4 * i
        if "F_%x" % addr not in used:
            continue
        print("theorem F_%x : fetch_word %s (BitVec.ofInt 64 0x%x) = some 0x%08x := by\n  decide\n"
              % (addr, segs, addr, word))
    for word in sorted(set(words)):
        if "D_%08x" % word not in used:
            continue
        print("theorem D_%08x : decodeAny 0x%08x = some (%s, 4) := by\n  decide\n"
              % (word, word, decoded[word]))
    print("end %s" % module)


if __name__ == "__main__":
    main()
